    /** 运行时扩充词表（词组级） */
    @Volatile
    private var extraPhrases: Map<String, String> = emptyMap()

    /** 运行时扩充词表（单字级） */
    @Volatile
    private var extraChars: Map<Char, Char> = emptyMap()

    /** 扩充接口：外部可注入补充词表而不修改核心逻辑 */
    fun appendEntries(phrases: Map<String, String> = emptyMap(), chars: Map<Char, Char> = emptyMap()) {
        extraPhrases = extraPhrases + phrases
        extraChars = extraChars + chars
    }

    /** 单字查询（含扩充表） */
    fun convertChar(c: Char): Char? = extraChars[c] ?: CHAR_MAP[c]

    /** 是否包含任何繁体字（快速检测；无繁体文本直接跳过转换，零开销短路） */
    fun containsTraditional(text: String): Boolean {
        for (c in text) {
            if (c in CHAR_MAP || c in extraChars) return true
        }
        return false
    }

    /**
     * 三级转换查找：词组映射 → 词组保留 → 单字
     * @return 查找结果；null 表示该位置无需处理
     */
    fun lookup(text: String, start: Int): LookupResult? {
        // 1. 词组优先（最长匹配：PHRASE_MAP 与扩充词组合并查询）
        for (len in 4 downTo 2) {
            if (start + len > text.length) continue
            val seg = text.substring(start, start + len)
            val mapped = extraPhrases[seg] ?: PHRASE_MAP[seg]
            if (mapped != null) return LookupResult(mapped, len)
            if (seg in PHRASE_KEEP) return LookupResult(seg, len) // 保留原样
        }
        // 2. 单字
        val c = text[start]
        val mappedChar = convertChar(c)
        if (mappedChar != null && mappedChar != c) return LookupResult(mappedChar.toString(), 1)
        return null
    }

    /** 查找结果：替换文本 + 消费长度 */
    data class LookupResult(val replacement: String, val consumed: Int)
